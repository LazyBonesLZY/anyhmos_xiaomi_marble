#!/usr/bin/env python3
"""Generate the AGM passthrough trampolines and slot metadata.

One source of truth: ``agm_symbols.txt`` (the public AGM C API that
``libagmclient.so`` exports, harvested from its dynamic symbol table).  The
generator emits two compile units so the symbol list can never drift between
the assembly trampolines and the C resolver:

  * ``agmipc_shim_syms.h``   - X-macro list of symbols with slot indices
  * ``agmipc_shim_syms.S``   - one register-transparent trampoline per symbol

The trampolines deliberately do not encode any prototype: they load the
resolved function pointer from the slot table and branch to it, leaving
x0..x7 untouched.  No AGM header is required and no ABI is re-declared.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

HEADER_BANNER = "/* auto-generated by gen_shim_sources.py - do not edit */"
ASM_BANNER = "/* auto-generated by gen_shim_sources.py - do not edit */"


def read_symbols(path: pathlib.Path) -> list[str]:
    symbols = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if not line.startswith("agm_"):
            raise SystemExit(f"unexpected symbol {line!r} in {path}")
        symbols.append(line)
    if not symbols:
        raise SystemExit(f"no symbols found in {path}")
    if len(set(symbols)) != len(symbols):
        raise SystemExit(f"duplicate symbols in {path}")
    return symbols


def emit_header(symbols: list[str]) -> str:
    rows = [f"    X({name}, {index}) \\" for index, name in enumerate(symbols)]
    return "\n".join(
        [
            HEADER_BANNER,
            "#ifndef AGMIPC_SHIM_SYMS_H",
            "#define AGMIPC_SHIM_SYMS_H",
            "",
            "/* X(name, slot_index) */",
            "#define AGMIPC_SYM_LIST(X) \\",
            *rows,
            "",
            f"#define AGMIPC_SYM_COUNT {len(symbols)}",
            "",
            "#endif",
            "",
        ]
    )


def emit_asm(symbols: list[str]) -> str:
    out = [
        ASM_BANNER,
        "/* Each trampoline is 4 instructions: slot lookup then indirect branch.",
        " * hint #32 is `bti c`, so the entry point stays valid if the link",
        " * gains the BTI property. */",
        "",
        "\t.text",
    ]
    for index, name in enumerate(symbols):
        out += [
            "",
            f"\t.globl {name}",
            f"\t.type {name}, %function",
            f"\t.p2align 2",
            f"{name}:",
            "\thint\t#32",
            "\tadrp\tx16, g_agmipc_slots",
            "\tadd\tx16, x16, :lo12:g_agmipc_slots",
            f"\tldr\tx16, [x16, #{index * 8}]",
            "\tbr\tx16",
            f"\t.size {name}, .-{name}",
        ]
    out += ["", '\t.section\t.note.GNU-stack,"",%progbits', ""]
    return "\n".join(out)


def emit_names(symbols: list[str]) -> str:
    rows = [f'    "{name}",' for name in symbols]
    return "\n".join(
        [
            HEADER_BANNER,
            "#ifndef AGMIPC_SHIM_NAMES_H",
            "#define AGMIPC_SHIM_NAMES_H",
            "",
            "static const char *const g_agmipc_names[AGMIPC_SYM_COUNT] = {",
            *rows,
            "};",
            "",
            "#endif",
            "",
        ]
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--symbols", required=True, type=pathlib.Path)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path)
    args = parser.parse_args(argv)

    symbols = read_symbols(args.symbols)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    artefacts = {
        "agmipc_shim_syms.h": emit_header(symbols),
        "agmipc_shim_syms.S": emit_asm(symbols),
        "agmipc_shim_names.h": emit_names(symbols),
    }
    for name, text in artefacts.items():
        target = args.out_dir / name
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
        print(f"generated {target} ({len(symbols)} symbols)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))